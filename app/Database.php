    /**
     * Завантажити список усіх дизайнів із врахуванням кастомних та змінених
     */
    public static function getDesignsData(bool $forceRefresh = false): array {
        if (!$forceRefresh && self::$designs !== null) {
            return self::$designs;
        }

        $cacheFile = Config::getCacheDir() . 'designs_catalog.json';
        if (!$forceRefresh && file_exists($cacheFile)) {
            $cached = json_decode(file_get_contents($cacheFile), true);
            if (!empty($cached)) {
                self::$designs = $cached;
                return self::$designs;
            }
        }

        $categories = self::getCategoriesData();
        $catMap = [];
        foreach ($categories as $c) {
            $catMap[$c['slug']] = $c;
        }

        $customDesigns = self::getCustomDesigns();
        $designDir = dirname(__DIR__) . '/design';
        $designsMap = [];

        // 1. Сканування папки design/
        if (is_dir($designDir)) {
            $folders = scandir($designDir);
            foreach ($folders as $folder) {
                if ($folder === '.' || $folder === '..' || !is_dir($designDir . '/' . $folder)) continue;

                $catInfo = $catMap[$folder] ?? [
                    'slug' => $folder,
                    'name' => ucfirst(str_replace('-', ' ', $folder)),
                    'icon' => '🎨',
                ];

                $files = scandir($designDir . '/' . $folder);
                foreach ($files as $file) {
                    if (!preg_match('/^(\d+)/', $file, $m)) continue;
                    $designId = (int)$m[1];

                    $meta = self::DESIGNS_METADATA[$designId] ?? null;
                    $name = $meta['name'] ?? "{$catInfo['name']} #{$designId}";
                    $tags = $meta['tags'] ?? [];
                    $isTop = ($folder === 'made-in-ukraine' || ($designId % 9 === 0) || in_array($designId, [825, 932, 5293, 2322, 6109])) ? 1 : 0;

                    $designsMap[$designId] = [
                        'id'            => $designId,
                        'category_slug' => $folder,
                        'category_name' => $catInfo['name'],
                        'category_icon' => $catInfo['icon'],
                        'name'          => $name,
                        'tags'          => $tags,
                        'image_path'    => "/design/{$folder}/{$file}",
                        'is_top'        => $isTop,
                    ];
                }
            }
        }

        // 2. Застосування кастомних змін та нових принтів з custom_designs.json
        foreach ($customDesigns as $cId => $cData) {
            $cId = (int)$cId;
            if (!empty($cData['is_deleted'])) {
                unset($designsMap[$cId]);
                continue;
            }

            $catSlug = $cData['category_slug'] ?? ($designsMap[$cId]['category_slug'] ?? 'other');
            $catInfo = $catMap[$catSlug] ?? [
                'slug' => $catSlug,
                'name' => ucfirst(str_replace('-', ' ', $catSlug)),
                'icon' => '🎨',
            ];

            $img = $cData['image_path'] ?? ($designsMap[$cId]['image_path'] ?? "/design/{$catSlug}/{$cId}u-4029.jpg");
            $name = $cData['name'] ?? ($designsMap[$cId]['name'] ?? "Принт #{$cId}");
            $tags = $cData['tags'] ?? ($designsMap[$cId]['tags'] ?? []);
            $isTop = isset($cData['is_top']) ? (int)$cData['is_top'] : ($designsMap[$cId]['is_top'] ?? 0);

            $designsMap[$cId] = [
                'id'            => $cId,
                'category_slug' => $catSlug,
                'category_name' => $catInfo['name'],
                'category_icon' => $catInfo['icon'],
                'name'          => $name,
                'tags'          => $tags,
                'image_path'    => $img,
                'is_top'        => $isTop,
            ];
        }

        // 3. Інтеграція товарів та принтів з XML/CSV флуду (xml_catalog.json)
        $xmlCatalogFile = Config::getCacheDir() . 'xml_catalog.json';
        if (file_exists($xmlCatalogFile)) {
            $xmlJson = @file_get_contents($xmlCatalogFile);
            $xmlData = json_decode($xmlJson ?: '', true);
            if (!empty($xmlData['items']) && is_array($xmlData['items'])) {
                foreach ($xmlData['items'] as $xmlItem) {
                    $rawId = (string)($xmlItem['id'] ?? '');
                    $numericId = (int)preg_replace('/^(\d+).*/', '$1', $rawId);
                    if ($numericId <= 0) continue;

                    // Якщо цього принта ще немає в базі або він потребує оновлення
                    if (!isset($designsMap[$numericId])) {
                        $catSlug = (string)($xmlItem['category_slug'] ?? 'other');
                        $catName = (string)($xmlItem['category_name'] ?? 'Різне');

                        $catInfo = $catMap[$catSlug] ?? [
                            'slug' => $catSlug,
                            'name' => $catName,
                            'icon' => '🎨',
                        ];

                        $img = !empty($xmlItem['picture']) ? $xmlItem['picture'] : "/design/{$catSlug}/{$numericId}u-4029.jpg";
                        $designName = !empty($xmlItem['name']) ? $xmlItem['name'] : "Принт #{$numericId}";

                        // Збираємо теги для пошуку
                        $tags = [$catInfo['name']];
                        if (!empty($xmlItem['params']['Назва дизайну'])) {
                            $tags[] = $xmlItem['params']['Назва дизайну'];
                        }
                        if (!empty($xmlItem['params']['Матеріал'])) {
                            $tags[] = $xmlItem['params']['Матеріал'];
                        }

                        $designsMap[$numericId] = [
                            'id'            => $numericId,
                            'category_slug' => $catSlug,
                            'category_name' => $catInfo['name'],
                            'category_icon' => $catInfo['icon'],
                            'name'          => $designName,
                            'tags'          => array_unique(array_filter($tags)),
                            'image_path'    => $img,
                            'is_top'        => 0,
                            'price'         => (float)($xmlItem['price'] ?? 229),
                        ];
                    }
                }
            }
        }

        $designs = array_values($designsMap);

        if (!is_dir(Config::getCacheDir())) {
            mkdir(Config::getCacheDir(), 0755, true);
        }
        file_put_contents($cacheFile, json_encode($designs, JSON_UNESCAPED_UNICODE));

        self::$designs = $designs;
        return self::$designs;
    }

