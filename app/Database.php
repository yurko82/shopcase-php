    /**
     * Завантажити список усіх 238 дизайнів із локальної папки design/ або кешу
     */
    /**
     * Отримати повний список категорій (вбудовані + додані через адмінку)
     */
    public static function getCategoriesData(): array {
        if (self::$categories !== null) {
            return self::$categories;
        }

        $cats = self::CATEGORIES_DATA;
        $customFile = dirname(__DIR__) . '/data/custom_categories.json';

        if (file_exists($customFile)) {
            $customCats = json_decode(file_get_contents($customFile), true);
            if (is_array($customCats)) {
                $catMap = [];
                foreach ($cats as $c) {
                    $catMap[$c['slug']] = $c;
                }
                foreach ($customCats as $cc) {
                    $slug = (string)($cc['slug'] ?? '');
                    if (!$slug) continue;
                    if (!empty($cc['is_deleted'])) {
                        unset($catMap[$slug]);
                    } else {
                        $catMap[$slug] = array_merge($catMap[$slug] ?? [], $cc);
                    }
                }
                $cats = array_values($catMap);
            }
        }

        usort($cats, fn($a, $b) => ($a['sort'] ?? 99) <=> ($b['sort'] ?? 99));
        self::$categories = $cats;
        return self::$categories;
    }

    /**
     * Зберегти категорію (додавання або редагування)
     */
    public static function saveCategory(array $category): bool {
        $slug = trim(preg_replace('/[^a-z0-9_-]/i', '', strtolower((string)($category['slug'] ?? ''))));
        if (!$slug) return false;

        $customFile = dirname(__DIR__) . '/data/custom_categories.json';
        $customCats = file_exists($customFile) ? (json_decode(file_get_contents($customFile), true) ?: []) : [];

        $record = [
            'slug' => $slug,
            'name' => trim((string)($category['name'] ?? ucfirst($slug))),
            'icon' => trim((string)($category['icon'] ?? '🎨')),
            'sort' => (int)($category['sort'] ?? 50),
        ];

        $found = false;
        foreach ($customCats as &$c) {
            if ($c['slug'] === $slug) {
                $c = array_merge($c, $record);
                unset($c['is_deleted']);
                $found = true;
                break;
            }
        }
        if (!$found) {
            $customCats[] = $record;
        }

        if (!is_dir(dirname($customFile))) mkdir(dirname($customFile), 0755, true);
        file_put_contents($customFile, json_encode($customCats, JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT), LOCK_EX);

        self::clearCache();
        return true;
    }

    /**
     * Видалити або приховати категорію
     */
    public static function deleteCategory(string $slug): bool {
        $slug = trim(strtolower($slug));
        if (!$slug) return false;

        $customFile = dirname(__DIR__) . '/data/custom_categories.json';
        $customCats = file_exists($customFile) ? (json_decode(file_get_contents($customFile), true) ?: []) : [];

        $found = false;
        foreach ($customCats as &$c) {
            if ($c['slug'] === $slug) {
                $c['is_deleted'] = true;
                $found = true;
                break;
            }
        }
        if (!$found) {
            $customCats[] = ['slug' => $slug, 'is_deleted' => true];
        }

        if (!is_dir(dirname($customFile))) mkdir(dirname($customFile), 0755, true);
        file_put_contents($customFile, json_encode($customCats, JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT), LOCK_EX);

        self::clearCache();
        return true;
    }

