    /**
     * Зберегти принт (додавання нового або оновлення існуючого)
     */
    public static function saveDesign(array $design): bool {
        $id = (int)($design['id'] ?? 0);
        if ($id <= 0) return false;

        $customFile = dirname(__DIR__) . '/data/custom_designs.json';
        $customDesigns = self::getCustomDesigns();

        $tags = $design['tags'] ?? [];
        if (is_string($tags)) {
            $tags = array_values(array_filter(array_map('trim', explode(',', $tags))));
        }

        $record = [
            'id'            => $id,
            'name'          => trim((string)($design['name'] ?? "Принт #{$id}")),
            'category_slug' => trim((string)($design['category_slug'] ?? 'other')),
            'tags'          => $tags,
            'is_top'        => !empty($design['is_top']) ? 1 : 0,
            'updated_at'    => date('Y-m-d H:i:s'),
        ];

        if (!empty($design['image_path'])) {
            $record['image_path'] = (string)$design['image_path'];
        }

        $customDesigns[$id] = array_merge($customDesigns[$id] ?? [], $record);
        unset($customDesigns[$id]['is_deleted']);

        if (!is_dir(dirname($customFile))) mkdir(dirname($customFile), 0755, true);
        file_put_contents($customFile, json_encode($customDesigns, JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT), LOCK_EX);

        self::clearCache();
        return true;
    }

