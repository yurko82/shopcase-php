    public static function updateOrder(mixed $orderId, array $updates): bool {
        $file = dirname(__DIR__) . '/data/orders.json';
        $orders = self::getOrders();
        $updated = false;

        foreach ($orders as &$o) {
            if ((string)($o['id'] ?? '') === (string)$orderId || (string)($o['endorphone_order_id'] ?? '') === (string)$orderId) {
                foreach ($updates as $k => $v) {
                    $o[$k] = $v;
                }
                $o['updated_at'] = date('Y-m-d H:i:s');
                $updated = true;
                break;
            }
        }

        if ($updated) {
            file_put_contents($file, json_encode($orders, JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT), LOCK_EX);
        }
        return $updated;
    }

    public static function deleteOrder(mixed $orderId): bool {
        $file = dirname(__DIR__) . '/data/orders.json';
        $orders = self::getOrders();
        $filtered = array_values(array_filter($orders, fn($o) => (string)($o['id'] ?? '') !== (string)$orderId && (string)($o['endorphone_order_id'] ?? '') !== (string)$orderId));
        if (count($filtered) !== count($orders)) {
            file_put_contents($file, json_encode($filtered, JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT), LOCK_EX);
            return true;
        }
        return false;
    }
